// Writes src/lessons/generated/animations.ts: one `() => import("...")` per lesson animation file,
// so the browser loads each animation as its own small chunk (src/lessons/LessonAnimation.tsx).
// Turbopack bundles the targets of a single import.meta.glob into one chunk, which would ship every
// lesson's animations with every lesson. Runs before `next dev` and `next build` (package.json).
import fs from "node:fs";
import path from "node:path";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const lessons = path.join(root, "src", "lessons");
const out = path.join(lessons, "generated", "animations.ts");

const entries = [];
for (const folder of fs.readdirSync(lessons).sort()) {
  const dir = path.join(lessons, folder, "animations");
  if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith(".tsx")) continue;
    const head = fs.readFileSync(path.join(dir, file), "utf8").slice(0, 200);
    if (!/^\s*["']use client["']/.test(head)) continue;
    const id = `${folder}/animations/${file.replace(/\.tsx$/, "")}`;
    entries.push(`  ${JSON.stringify(id)}: () => import(${JSON.stringify(`../${id}`)}),`);
  }
}

const source = `// Generated by scripts/gen-animation-registry.mjs (runs before dev and build). Do not edit.
// One loader per lesson animation file, so each loads as its own chunk.

export const ANIMATIONS: Record<string, () => Promise<Record<string, unknown>>> = {
${entries.join("\n")}
};
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
const previous = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
if (previous !== source) fs.writeFileSync(out, source);
console.log(`[animations] ${entries.length} lesson animation files registered`);
